/**
 * El esquema vive acá y no en un .sql suelto a propósito.
 *
 * Leerlo con readFile(process.cwd() + '/lib/schema.sql') funciona local, pero
 * en Vercel la función serverless no incluye ese archivo: la ruta se arma en
 * runtime y el tracer de Next no la ve. Como constante de TypeScript viaja
 * siempre con el código.
 */

export const SENTENCIAS: string[] = [
  `create table if not exists ingredientes (
     id                text primary key,
     nombre            text not null,
     precio            numeric(14, 2) not null default 0,
     unidad            text not null check (unidad in ('KG', 'LITRO', 'UNIDAD')),
     categoria         text not null default 'Básicos',
     precio_confirmado boolean not null default false,
     actualizado       timestamptz,
     notas             text,
     creado            timestamptz not null default now()
   )`,

  `create unique index if not exists ingredientes_nombre_unico
     on ingredientes (lower(trim(nombre)))`,

  `create table if not exists recetas (
     id          text primary key,
     numero      integer generated by default as identity,
     nombre      text not null,
     descripcion text not null default '',
     rinde       numeric(14, 2),
     margen      numeric(8, 4) not null default 0,
     fecha       timestamptz not null default now(),
     actualizado timestamptz not null default now()
   )`,

  `create table if not exists receta_ingredientes (
     id             text primary key,
     receta_id      text not null references recetas (id) on delete cascade,
     ingrediente_id text references ingredientes (id) on delete set null,
     cantidad       numeric(14, 2),
     orden          integer not null default 0
   )`,

  `create index if not exists receta_ingredientes_receta
     on receta_ingredientes (receta_id)`,

  `create table if not exists receta_mano_obra (
     id         text primary key,
     receta_id  text not null references recetas (id) on delete cascade,
     concepto   text not null default '',
     horas      numeric(10, 2),
     valor_hora numeric(14, 2),
     orden      integer not null default 0
   )`,

  `create index if not exists receta_mano_obra_receta
     on receta_mano_obra (receta_id)`,

  `create table if not exists receta_extras (
     id        text primary key,
     receta_id text not null references recetas (id) on delete cascade,
     concepto  text not null default '',
     monto     numeric(14, 2),
     orden     integer not null default 0
   )`,

  `create index if not exists receta_extras_receta
     on receta_extras (receta_id)`,

  `create table if not exists ajustes (
     clave text primary key,
     valor text not null
   )`,
]
