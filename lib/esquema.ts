/**
 * El esquema vive acá y no en un .sql suelto a propósito.
 *
 * Leerlo con readFile(process.cwd() + '/lib/schema.sql') funciona local, pero
 * en Vercel la función serverless no incluye ese archivo: la ruta se arma en
 * runtime y el tracer de Next no la ve. Como constante de TypeScript viaja
 * siempre con el código.
 *
 * Está versionado porque la base ya está en producción: agregar una columna
 * necesita un ALTER, y `create table if not exists` no lo hace. Cada versión
 * corre una sola vez y queda anotada en `ajustes.esquema_version`.
 *
 * Para agregar algo: sumá una versión nueva al final. Nunca edites una que ya
 * se aplicó, porque las bases que la corrieron no la vuelven a ejecutar.
 */

